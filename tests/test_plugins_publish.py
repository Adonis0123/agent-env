PUBLIC_REPO = {"visibility": "public", "empty": None, "via": "gh", "error": None, "fix": None}
PRIVATE_REPO = {"visibility": "private", "empty": None, "via": "gh", "error": None, "fix": None}
UNKNOWN_REPO = {"visibility": "unknown", "empty": None, "via": None, "error": "gh 没查到：offline",
                "fix": "确认能联网并已登录（gh auth login）"}


class PublishBase(PluginBase):
    def setUp(self):
        super().setUp()
        self.remote = self.root / "remote.git"
        subprocess.run(["git", "init", "-q", "--bare", "-b", "main", str(self.remote)], check=True)
        # the manifest only takes https addresses: git rewrites this one to the local bare repository
        self.url = "https://git.example.test/owner/agent-plugin"
        env = mock.patch.dict("os.environ", {"GIT_CONFIG_COUNT": "1", "GIT_CONFIG_KEY_0": f"url.{self.remote}.insteadOf",
                                             "GIT_CONFIG_VALUE_0": self.url})
        env.start()
        self.addCleanup(env.stop)
        self.seen = dict(PUBLIC_REPO)
        probe = mock.patch.object(plugins, "_remote_visibility", side_effect=lambda url: self.seen)
        self.probe = probe.start()
        self.addCleanup(probe.stop)

    def make(self, which="pub"):
        pub = dict(PUBLIC, repo=self.url) if which == "pub" else PUBLIC
        per = dict(PERSONAL, repo=self.url) if which == "per" else PERSONAL
        return self.setup({"pub": pub, "per": per})

    def publish(self, m, name="pub", yes=False):
        out = io.StringIO()
        return plugins.publish(m, [name], self.rules(), out, yes=yes), out.getvalue()

    def steps(self, name="pub"):
        return sorted(json.loads(plugins.ledger_path().read_text())["plugins"][name]["steps"])

    def remote_files(self):
        if not git(self.remote, "for-each-ref", "refs/heads"):
            return None
        return sorted(git(self.remote, "ls-tree", "-r", "--name-only", "main").split())

    def remote_log(self):
        return git(self.remote, "log", "--format=%s|%ae", "main").splitlines()

    def other_clone(self):
        """Someone else's clone of the remote, to change it behind publish's back."""
        other = self.root / "other"
        subprocess.run(["git", "clone", "-q", str(self.remote), str(other)], check=True, capture_output=True)
        return other


class CommitAndPushTests(PublishBase):
    def test_empty_remote_gets_one_commit_with_exactly_the_generated_files(self):
        m = self.make()
        rc, text = self.publish(m, yes=True)
        self.assertEqual(rc, 0, text)
        self.assertIn("commit 完成，已提交", text)
        self.assertIn("push 完成，已推送 1 个提交", text)
        built = sorted(plugins.tree_files(plugins.output_dir(m, "pub")))
        self.assertEqual(self.remote_files(), built)
        self.assertEqual(self.remote_log(), ["✨ feat: update the pub plugin generated by agent-env|t@example.test"])
        self.assertEqual(self.steps(), ["build", "commit", "push", "scan"])
        self.assertTrue(plugins.clone_dir("pub").joinpath(".git").is_dir())
        self.assertFalse((plugins.output_dir(m, "pub") / ".git").exists(), "the build output stays a plain dir")
        state = plugins_view.plugin_state(m, "pub", self.rules(), plugins.read_ledger())
        self.assertEqual(state["publish"]["state"], "pushed")

    def test_push_tells_the_panel_the_repo_is_not_empty(self):
        key = plugins_view.repo_key(self.url)
        other = {"visibility": "private", "empty": False, "via": "gh", "checked_at": "2026-11-01T00:00:00Z"}
        plugins_view._write_cache({key: dict(PUBLIC_REPO, empty=True, checked_at="2026-11-01T00:00:00Z"),
                                   "github.com/me/other": other}, "2026-11-01T00:00:00Z")
        self.seen = dict(PUBLIC_REPO, empty=True)  # the host still said empty just before the push
        rc, text = self.publish(self.make(), yes=True)
        self.assertEqual(rc, 0, text)
        cache = plugins_view.read_cache()
        self.assertIs(cache[key]["empty"], False)
        self.assertEqual(cache[key]["visibility"], "public")
        self.assertNotEqual(cache[key]["checked_at"], "2026-11-01T00:00:00Z")
        self.assertEqual(cache["github.com/me/other"], other)

    def test_no_change_makes_no_commit_and_counts_as_pushed_without_yes(self):
        m = self.make()
        self.publish(m, yes=True)
        plugins.ledger_path().unlink()
        shutil.rmtree(plugins.clone_dir("pub"))  # a fresh clone, like a new machine
        self.probe.reset_mock()
        rc, text = self.publish(m)
        self.assertEqual(rc, 0, text)
        self.assertIn("已是最新，无需提交", text)
        self.assertIn("无需推送", text)
        self.assertEqual(len(self.remote_log()), 1)
        self.assertEqual(self.steps(), ["build", "commit", "push", "scan"])
        self.assertEqual(plugins_view.plugin_state(m, "pub", self.rules(), plugins.read_ledger())["publish"]["state"],
                         "pushed")
        self.probe.assert_not_called()  # nothing to push: no need to ask the host

    def test_mirror_deletes_files_no_longer_generated(self):
        m = self.make()
        self.publish(m, yes=True)
        other = self.other_clone()
        (other / "stale.txt").write_text("old\n")
        (other / "old-dir").mkdir()
        (other / "old-dir" / "x.md").write_text("old\n")
        git(other, "add", "-A")
        git(other, "commit", "-q", "-m", "extra")
        git(other, "push", "-q", "origin", "main")
        plugins.ledger_path().unlink()
        rc, text = self.publish(m, yes=True)
        self.assertEqual(rc, 0, text)
        self.assertNotIn("stale.txt", self.remote_files())
        self.assertNotIn("old-dir/x.md", self.remote_files())
        self.assertEqual(self.remote_files(), sorted(plugins.tree_files(plugins.output_dir(m, "pub"))))
        self.assertEqual(len(self.remote_log()), 3, "a new commit on top, never a rewrite")

    def test_dry_run_lists_and_stops_then_yes_resumes_from_the_ledger(self):
        m = self.make()
        rc, text = self.publish(m)
        self.assertEqual(rc, 1)
        self.assertIn(f"演练，将推送到 {self.url}（main；仓库公开，插件公开）", text)
        self.assertIn("提交 ", text)
        self.assertIn("A\tAGENTS.md", text)
        self.assertIn("加 --yes 才推送：bin/agent-env plugin publish --plugin pub --yes", text)
        self.assertIsNone(self.remote_files(), "nothing left this machine")
        self.assertEqual(self.steps(), ["build", "commit", "scan"])
        self.assertEqual(plugins_view.plugin_state(m, "pub", self.rules(), plugins.read_ledger())["publish"]["state"],
                         "not_pushed")
        with mock.patch.object(plugins, "_step_commit", side_effect=AssertionError("commit must not rerun")), \
                mock.patch.dict(plugins.STEPS, {"commit": plugins._step_commit}):
            rc, text = self.publish(m, yes=True)
        self.assertEqual(rc, 0, text)
        self.assertIn("commit 已完成", text)
        self.assertIn("push 完成，已推送 1 个提交", text)
        self.assertEqual(len(self.remote_log()), 1)

    def test_personal_plugin_never_goes_to_a_public_repo(self):
        m = self.make("per")
        rc, text = self.publish(m, "per")
        self.assertEqual(rc, 1)
        self.assertIn("加 --yes 也会被拒", text)
        with self.assertRaisesRegex(plugins.PluginError, "公开仓库，个人插件绝不推送到公开仓。修复："):
            self.publish(m, "per", yes=True)
        self.assertIsNone(self.remote_files())
        self.assertNotIn("push", self.steps("per"))
        self.seen = dict(PRIVATE_REPO)
        rc, text = self.publish(m, "per", yes=True)
        self.assertEqual(rc, 0, text)
        self.assertIsNotNone(self.remote_files())

    def test_unknown_visibility_refuses(self):
        self.seen = dict(UNKNOWN_REPO)
        m = self.make()
        with self.assertRaisesRegex(plugins.PluginError, "查不到 .* 是公开还是私有（gh 没查到：offline），不推送。修复：确认能联网"):
            self.publish(m, yes=True)
        self.assertIsNone(self.remote_files())

    def test_non_fast_forward_is_an_error_never_a_force_push(self):
        m = self.make()
        self.publish(m, yes=True)
        (self.root / "AGENTS.md").write_text(self.rules().replace("shared body", "v2"), encoding="utf-8")
        self.publish(m)  # commits v2 locally, dry run
        other = self.other_clone()
        (other / "theirs.txt").write_text("theirs\n")
        git(other, "add", "-A")
        git(other, "commit", "-q", "-m", "theirs")
        git(other, "push", "-q", "origin", "main")
        with self.assertRaisesRegex(plugins.PluginError, "不是快进），不会强推。修复：.*reset --hard origin/main"):
            self.publish(m, yes=True)
        self.assertEqual(self.remote_log()[0], "theirs|t@example.test", "their commit is still on top")
        clone = plugins.clone_dir("pub")
        git(clone, "reset", "-q", "--hard", "origin/main")  # the fix the error gives
        rc, text = self.publish(m, yes=True)
        self.assertEqual(rc, 0, text)
        self.assertIn("commit 完成，已提交", text, "the recorded commit no longer stands, so it reruns")
        self.assertNotIn("theirs.txt", self.remote_files())
        self.assertEqual(self.remote_log()[1], "theirs|t@example.test")

    def test_without_repo_stops_at_commit_with_the_fix(self):
        m = self.setup({"pub": PUBLIC, "per": PERSONAL})
        rc, text = self.publish(m, yes=True)
        self.assertEqual(rc, 1)
        self.assertIn("停在 commit：清单 [plugins.pub] 没有 repo。修复：先建仓并在清单写 repo", text)


class IdentityTests(PublishBase):
    def test_github_commits_as_the_owners_noreply_address(self):
        with mock.patch.object(plugins, "_github_id", return_value="123"):
            name, email = plugins._identity("https://github.com/Someone/agent-plugin-x")
        self.assertEqual(email, "123+Someone@users.noreply.github.com")
        self.assertEqual(name, "Someone")  # no global user.name in the tests

    def test_github_without_an_id_refuses(self):
        with mock.patch.object(plugins, "_github_id", return_value=None):
            with self.assertRaisesRegex(plugins.PluginError, "noreply.*修复：确认 gh 已登录"):
                plugins._identity("git@github.com:Someone/agent-plugin-x.git")

    def test_other_hosts_use_the_global_identity(self):
        self.assertIsNone(plugins._identity(self.url))  # none set: git decides


