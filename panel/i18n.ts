export function translator(lang: Lang): T {
  return (s, vars) => {
    let out = lang === "zh" ? (ZH[s] ?? s) : s;
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
    return out;
  };
}
